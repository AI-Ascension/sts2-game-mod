using System;
using System.Collections.Generic;

namespace AiAscension.Sts2GameMod.Runtime;

internal sealed record LegalActionReference(
    string ActionId,
    string Kind,
    string? Value,
    string? TargetId,
    ulong Generation)
{
    internal bool Validate(out string error)
    {
        if (!RuntimeV3GameplayContract.IsIdentity(ActionId)
            || !RuntimeV3GameplayContract.IsIdentity(Kind)
            || Value is not null && !RuntimeV3GameplayContract.IsIdentity(Value)
            || TargetId is not null && !RuntimeV3GameplayContract.IsIdentity(TargetId))
        {
            error = "legal action contains an invalid identity";
            return false;
        }
        if (Generation > RuntimeV3GameplayContract.MaxGeneration)
        {
            error = "legal action generation exceeds its bound";
            return false;
        }
        switch (Kind)
        {
            case "start_run" or "select_map_node" or "choose_reward" or "shop_purchase"
                or "shop_remove" or "smith" or "event_choice" or "select_card":
                if (Value is null || TargetId is not null)
                {
                    error = "argument action is missing its typed value or has an unexpected target";
                    return false;
                }
                break;
            case "play_card":
                if (Value is null)
                {
                    error = "play_card action is missing its card identity";
                    return false;
                }
                break;
            case "end_turn" or "skip_reward" or "rest" or "confirm_victory" or "save_quit":
                if (Value is not null || TargetId is not null)
                {
                    error = "argument-free action contains an unexpected argument";
                    return false;
                }
                break;
            default:
                error = "legal action kind is not part of the Runtime-v3 catalog";
                return false;
        }
        error = string.Empty;
        return true;
    }
}

/// <summary>Generation-bound catalog generated by the host, never by policy code.</summary>
internal sealed class LegalActionCatalog
{
    private readonly Dictionary<string, LegalActionReference> _actions;

    internal LegalActionCatalog(ulong generation, IReadOnlyList<LegalActionReference> actions)
    {
        Generation = generation;
        _actions = new Dictionary<string, LegalActionReference>(StringComparer.Ordinal);
        foreach (LegalActionReference action in actions)
        {
            if (action.Generation == generation && action.Validate(out _))
            {
                _actions.TryAdd(action.ActionId, action);
            }
        }
    }

    internal static bool TryCreate(
        ulong generation,
        IReadOnlyList<LegalActionReference> actions,
        out LegalActionCatalog? catalog)
    {
        catalog = null;
        if (actions.Count > RuntimeV3GameplayContract.MaxLegalActions)
        {
            return false;
        }
        var ids = new HashSet<string>(StringComparer.Ordinal);
        foreach (LegalActionReference action in actions)
        {
            if (action.Generation != generation
                || !action.Validate(out _)
                || !ids.Add(action.ActionId))
            {
                return false;
            }
        }
        catalog = new LegalActionCatalog(generation, actions);
        return true;
    }

    internal ulong Generation { get; }

    internal IReadOnlyCollection<LegalActionReference> Actions => _actions.Values;

    internal bool TryGet(string actionId, out LegalActionReference? action) =>
        _actions.TryGetValue(actionId, out action);

    internal bool ContainsExact(LegalActionReference action) =>
        _actions.TryGetValue(action.ActionId, out LegalActionReference? current)
        && current == action;
}
